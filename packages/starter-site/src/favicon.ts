/**
 * The owner's logo as a PNG data URI, from the file the build placed under
 * src/assets (the site root is the build's working directory), or undefined
 * when there is no logo or its file is not there.
 */
async function logoUri(path: string): Promise<string | undefined> {
  if (!path) return undefined
  const root = resolve(process.cwd(), "src/assets")
  const file = resolve(root, path.replace(/^\/?(?:src\/assets\/)?/, ""))
  // The field is written by the Developer, so a path that climbs out of the
  // assets folder reads nothing rather than any file the build can see.
  if (!file.startsWith(root + sep) || !existsSync(file)) return undefined
  const png = await sharp(readFileSync(file))
    .resize(128, 128, { fit: "inside" })
    .png()
    .toBuffer()
  return `data:image/png;base64,${png.toString("base64")}`
}

/** This site's mark: the owner's logo when there is one, else its initial. */
export async function siteMark(site: MarkSite): Promise<string> {
  return markSvg(
    site.businessName,
    markColours(site.palette, site.brandColor),
    await logoUri(site.logo)
  )
}

/**
 * The mark as a square PNG `size` pixels wide, rasterised from its outlines.
 * `opaque` fills the corners with the paper, as an apple-touch-icon must be:
 * iOS draws a transparent corner black and rounds the tile itself.
 */
export async function markPng(
  svg: string,
  size: number,
  paper: string,
  opaque: boolean
): Promise<Uint8Array<ArrayBuffer>> {
  const image = sharp(Buffer.from(svg), { density: (72 * size) / 64 }).resize(
    size,
    size
  )
  return new Uint8Array(
    await (opaque ? image.flatten({ background: paper }) : image)
      .png()
      .toBuffer()
  )
}
