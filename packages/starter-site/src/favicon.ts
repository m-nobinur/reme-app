export type MarkColours = { primary: string; paper: string }

/** The two colours of the mark, from site.palette, else site.brandColor, else the default theme's. */
export function markColours(palette: string, brandColor: string): MarkColours {
  const roles = paletteOf(palette) ?? paletteFromBrand(brandColor)
  return roles
    ? { primary: roles.primary, paper: roles.paper }
    : { primary: DEFAULT.primary, paper: DEFAULT.paper }
}

/** The first letter or figure of a name, upper case, or "" when it has none this set draws. */
export const initialOf = (name: string): string =>
  name
    .normalize("NFD")
    .toUpperCase()
    .match(/[A-Z0-9]/)?.[0] ?? ""

/**
 * The mark as a 64 unit SVG: a paper tile with a primary rim and the initial
 * in primary, 34 units tall so it still reads at 16 px. `image` is a data URI
 * of the owner's logo, drawn in place of the initial.
 */
export function markSvg(
  name: string,
  { primary, paper }: MarkColours,
  image?: string
): string {
  const glyph = GLYPHS[initialOf(name)]
  const scale = 0.34
  const inner = image
    ? `<image href="${image}" x="9" y="9" width="46" height="46" preserveAspectRatio="xMidYMid meet"/>`
    : glyph
      ? `<path fill="${primary}" transform="translate(${((64 - glyph[0] * scale) / 2).toFixed(2)} 15) scale(${scale})" d="${glyph[1]}"/>`
      : `<circle cx="32" cy="32" r="10" fill="${primary}"/>`
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect x="1.5" y="1.5" width="61" height="61" rx="14" fill="${paper}" stroke="${primary}" stroke-width="3"/>${inner}</svg>`
}

